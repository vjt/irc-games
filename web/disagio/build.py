#!/usr/bin/env python3
"""Write frasi.js for disagio.sniffo.org from love.py's DISAGIO_PHRASES.

The page shows the same pool `!disagio` draws from, so the list has one
source: love.py. It is read with ast, never imported (importing love.py
would pull in the bot). Run it after touching DISAGIO_PHRASES:

    python3 web/disagio/build.py

The site (disagio.sniffo.org) is this directory copied as-is into
m42:/srv/www/disagio.sniffo.org/, minus build.py and the Slopstrap README:

    rsync -rt --chmod=D755,F644 --exclude build.py \
        --exclude SLOPSTRAP-README.md web/disagio/ root@m42:/srv/www/disagio.sniffo.org/
"""
import ast
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
LOVE = HERE.parent.parent / "love.py"
OUT = HERE / "frasi.js"


def phrases():
    tree = ast.parse(LOVE.read_text(encoding="utf-8"))
    for node in tree.body:
        if (isinstance(node, ast.Assign) and len(node.targets) == 1
                and getattr(node.targets[0], "id", None) == "DISAGIO_PHRASES"):
            out = ast.literal_eval(node.value)
            bad = [p for p in out if "{to}" not in p or "{from}" in p]
            if bad:
                raise SystemExit(f"phrases without {{to}} or with {{from}}: {bad}")
            return out
    raise SystemExit(f"DISAGIO_PHRASES not found in {LOVE}")


def main():
    ps = phrases()
    OUT.write_text(
        "// Generated by build.py from love.py DISAGIO_PHRASES. Do not edit.\n"
        "window.DISAGIO = " + json.dumps(ps, ensure_ascii=False, indent=0) + ";\n",
        encoding="utf-8")
    print(f"{OUT.name}: {len(ps)} phrases")
    pools = {"it": ps, **check_translations(len(ps))}
    write_api(pools)


# The translated pools (<lang>/frasi.js) are written by hand from this one,
# one phrase per Italian phrase in the same order. They do not regenerate:
# when DISAGIO_PHRASES changes, this says which ones fell behind.
LANGS = ("en", "es", "fr", "pt", "ru", "zh", "ja")


def check_translations(n):
    bad, pools = [], {}
    for lang in LANGS:
        f = HERE / lang / "frasi.js"
        text = f.read_text(encoding="utf-8")
        got = json.loads(text[text.index("["):text.rindex("]") + 1])
        if len(got) != n or any("{to}" not in p for p in got):
            bad.append(f"{lang}: {len(got)} phrases, Italian has {n}")
        pools[lang] = got
    if bad:
        raise SystemExit("translations out of date: " + "; ".join(bad))
    return pools


# The "API": static JSON next to the site, so the server runs no code. One
# file per language plus an index. Picking at random is the client's job.
API = HERE / "api"


def write_api(pools):
    API.mkdir(exist_ok=True)
    for lang, ps in pools.items():
        doc = {"lang": lang, "count": len(ps), "placeholder": "{to}", "frasi": ps}
        body = json.dumps(doc, ensure_ascii=False, indent=1) + "\n"
        (API / f"frasi.{lang}.json").write_text(body, encoding="utf-8")
        if lang == "it":
            (API / "frasi.json").write_text(body, encoding="utf-8")
    index = {
        "about": "Il disagio, in JSON. Sostituisci {to} con un nick e pesca a caso.",
        "default": "/api/frasi.json",
        "langs": {lang: f"/api/frasi.{lang}.json" for lang in pools},
    }
    (API / "index.json").write_text(
        json.dumps(index, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"api/: {len(pools)} languages")


if __name__ == "__main__":
    main()
